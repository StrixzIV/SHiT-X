const ABSURD = new Set(['kW', 'MW', 'GW', 'TW', 'K-I', 'K-II', 'Ω'])
const LOW = new Set(['F', 'D', 'C', 'B'])

function variant(event, d) {
  if (event === 'tier' && d.tier) return ABSURD.has(d.tier) ? 'tier:absurd' : LOW.has(d.tier) ? 'tier:low' : 'tier:rich'
  const level = d.surroundings?.level ?? d.level
  if ((event === 'scene' || event === 'result') && level != null) return `${event}${level}`
  if (event === 'blocked') return /iOS/.test(d.why ?? '') ? 'blocked:ios' : 'blocked:geo'
  if (event === 'power' && d.answer) return /nothing/.test(d.answer) ? 'power:no' : 'power:yes'
  return null
}

const say = (t, d) => (typeof t === 'function' ? t(d) : t)

function banksFor(event, detail) {
  const s = detail.surroundings
  if (s && !canReact(event, s)) return []
  if (s?.phase === 'result') {
    if (s.level === 7) {
      if (!s.self.visible) {
        if (event === 'return') return [LINES['l7:inside-return']]
        if (event === 'cert') return [LINES['l7:inside-cert']]
        if (detail.subject !== 'buddy' && ['l7:swallow', 'l7:spit'].includes(event)) return [LINES[event.replace('l7:', 'l7:inside-card-')]]
        return [LINES['l7:inside']]
      }
      if (event === 'l7:swallow' && detail.subject === 'buddy') return [LINES['l7:spit']]
      // Existing l7:* physics events describe the result card. Her window has
      // its own motion; a caller can explicitly identify a window event.
      if (['l7:fling', 'l7:swallow', 'l7:spit'].includes(event) && detail.subject !== 'buddy') return [LINES[event.replace('l7:', 'l7:card-')]]
      if (['return', 'cert', 'poke'].includes(event)) return [LINES[`l7:${event}`]]
      if (event.startsWith('l7:') && !LINES[event]) return [LINES['l7:pulled']]
    }
    if (['return', 'poke'].includes(event)) return [LINES[`result:${event}`]]
  }
  if (s?.phase === 'scene' && event === 'return') return [LINES['scene:return']]
  const specific = LINES[variant(event, detail)]
  // The actual scene/result always wins over a random generic verdict.
  if (specific && ['scene', 'result'].includes(event)) return [specific]
  return [specific, LINES[event] || LINES.click].filter(Boolean)
}

// The prewritten lines for this moment, filled in, as "text [face]": DeepSeek may say
// one as-is, extend it, shorten it, or write its own (server/companion.js).
export function candidates(event, detail = {}) {
  const banks = banksFor(event, detail)
  const all = banks.flat().map(([t, face]) => `${say(t, detail)} [${face}]`)
  return [...new Set(all)].slice(0, 14)
}

export function fallbackLine(event, detail = {}, recent = []) {
  const banks = banksFor(event, detail)
  if (!banks.length) return { text: '', face: 'thinking' }
  const bank = banks.length > 1 && Math.random() >= 0.7 ? banks[banks.length - 1] : banks[0]
  const fresh = bank.filter(([t]) => !recent.includes(say(t, detail)))
  const pool = fresh.length ? fresh : bank
  const [t, face] = pool[Math.floor(Math.random() * pool.length)]
  return { text: say(t, detail), face }
}
